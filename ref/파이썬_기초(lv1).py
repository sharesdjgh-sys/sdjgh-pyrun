# 실습 예제: 로또 번호 생성기
import random
lotto = []
while True:
    temp = random.random()
    temp = temp * 100
    if temp >= 1 and temp < 46:
        lotto.append(int(temp))
        lotto = set(lotto)  # 중복 제거
        lotto = list(lotto)

    if len(lotto) == 6:
        break
print(lotto)

