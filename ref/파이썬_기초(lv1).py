# 클래스 정의
class Dog:
    def __init__(self, name, breed):  # 생성자 (초기화 메서드)
        self.name = name  # 인스턴스 변수 name 초기화
        self.breed = breed  # 인스턴스 변수 breed 초기화

    def bark(self):  # 메서드 정의
        print("Woof!")

# 첫 번째 강아지 인스턴스 생성
my_dog1 = Dog("Buddy", "Golden Retriever")

# 두 번째 강아지 인스턴스 생성
my_dog2 = Dog("Coco", "Poodle")

# 각 인스턴스의 속성 출력
print(my_dog1.name, my_dog1.breed)  # 출력: Buddy Golden Retriever
print(my_dog2.name, my_dog2.breed)  # 출력: Coco Poodle

# 각 인스턴스의 메서드 호출
my_dog1.bark()  # 출력: Woof!
my_dog2.bark()  # 출력: Woof!

class Character:  # 캐릭터의 기본 속성을 정의하는 부모 클래스
    def __init__(self, name, hp, power, attack_speed, attack_range): # __init__: 생성자 메서드로, 객체가 생성될 때 자동으로 호출됩니다.
        self.name = name  # self: 객체 자신을 가리키는 참조입니다.
        self.hp = hp  # 캐릭터의 체력
        self.power = power  # 캐릭터의 공격력
        self.attack_speed = attack_speed  # 캐릭터의 공격 속도
        self.attack_range = attack_range  # 캐릭터의 공격 거리
        self.is_alive = True  # 캐릭터의 생존 여부

    def attack(self):
        print(f"{self.name} 공격!")  # 캐릭터의 공격 동작, 기본적으로 "공격!" 메시지 출력

# 기본 캐릭터 인스턴스 생성
hero1 = Character("전사", "300", "50", "30", "2")
hero2 = Character("궁수", "200", "40", "15", "10")

# 기본 캐릭터 정보 출력
print(f"{hero1.name}: 체력 {hero1.hp}, 공격력 {hero1.power}, 공격속도 {hero1.attack_speed}, 공격거리 {hero1.attack_range}")
print(f"{hero2.name}: 체력 {hero2.hp}, 공격력 {hero2.power}, 공격속도 {hero2.attack_speed}, 공격거리 {hero2.attack_range}")

# 공격 메서드 실행
hero1.attack()  # 출력: 이름 생성: 공격!
hero2.attack()  # 출력: 이름 생성: 공격!

class Warrior(Character):  # 도끼병 캐릭터 자식 클래스 (Character 클래스 상속)
    def __init__(self, name):
        super().__init__(name, hp=100, power=80, attack_speed=70, attack_range=20) # super()는 부모 클래스의 메서드들을 호출할 수 있게 해주는 내장 함수

    def attack(self): # 메서드 오버라이딩(Method Overriding) - 부모 클래스의 메서드를 자식 클래스에서 재정의
        print(f"{self.name}: 돌격!")  # 도끼병 캐릭터의 공격 동작, "돌격!" 메시지 출력

class Archer(Character):  # 궁수 캐릭터 클래스 (Character 클래스 상속)
    def __init__(self, name):
        super().__init__(name, hp=50, power=30, attack_speed=30, attack_range=80) # 부모 클래스(Character)의 생성자를 호출, 기본 속성 설정, 낮은 체력, 낮은 공격력, 낮은 공격 속도, 높은 공격 거리

    def attack(self):
        print(f"{self.name}: 발사!")  # 궁수 캐릭터의 공격 동작, "발사!" 메시지 출력

